#!/usr/bin/env bash

LEVEL_COLORS=(
  "247;118;142" "242;129;134" "238;141;127" "233;152;119" "229;163;112"
  "224;175;104" "208;183;105" "191;191;105" "175;198;106" "158;206;106"
)

level_color() {
  local idx=$(( (${1:-0} - 1) / 10 ))
  (( idx < 0 )) && idx=0
  (( idx > 9 )) && idx=9
  printf '\033[38;2;%sm' "${LEVEL_COLORS[$idx]}"
}
